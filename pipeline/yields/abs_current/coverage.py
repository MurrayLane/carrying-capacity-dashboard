#!/usr/bin/env python3
"""Writes COVERAGE.md: for each of the model's 91 crop rows, what the current ABS cubes support, against the 2005-10 data.
Usage: MODELS_DIR=/path/to/Models python3 -I coverage.py      (run from this folder)"""
import json, os, re, sys, xlrd
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.join(HERE, '..'))
from yields import crop_year, norm
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
YEARS = ('2016-17', '2017-18', '2018-19', '2019-20', '2020-21')
regions = json.load(open(os.path.join(REPO, 'data/abs-2016-21/regions.json')))['regions']
cm = {c['crop']: c for c in json.load(open(os.path.join(HERE, 'commodity_map.json')))['crops']}
per = {}
for y in YEARS:
    d = json.load(open(os.path.join(REPO, 'data/abs-2016-21', f'cube_{y}.json')))
    cube = {norm(k): v for k, v in d['rows'].items()}; mask = {(norm(l), c) for l, c in d['unreliable']}
    for l, c in d['unreliable']:                      # a flag on any of area, trees or tonnes removes the yield
        for sfx in (' (ha)', ' trees (n)', ' (t)'):
            base = re.sub(r'( \(ha\)| trees \(n\)| \(t\))$', '', l); mask.add((norm(base + sfx), c))
    per[y] = (cube, mask)
old = xlrd.open_workbook(os.path.join(os.environ['MODELS_DIR'], 'Yield data', '5 NRM-all 5 years - average.xls')).sheet_by_name('Aver-add')
oldn = {str(old.cell_value(r, 0)).replace(' (t/ha)', '').strip(): sum(isinstance(old.cell_value(r, c), float) and old.cell_value(r, c) > 0 for c in range(2, 61)) for r in range(1, 92)}
lines = ['# Coverage of the current ABS cubes against the model\'s 91 crop rows', '',
 'Generated by `coverage.py`. A zone-year counts when the ABS gives both area (or trees) and tonnes, neither is marked unreliable (`**`), and the yield is positive.',
 'The 2005-10 column counts the 59 zones (excluding Australia) that had an averaged yield in the archive. The new count is of the 63 states and NRM regions.', '',
 '| Crop | Status | Years published | Zones with a yield, per year | Zones with 3 or more years | 2005-10 zones | Note |', '|---|---|---|---|---|---|---|']
tot_direct = 0
for name, c in cm.items():
    if c['status'] == 'absent': lines.append(f"| {name} | absent | 0 | | 0 | {oldn.get(name, 0)} | {c['note']} |"); continue
    counts = []; yrs = 0; per_zone = {}
    for y in YEARS:
        cube, mask = per[y]
        g = crop_year(cube, name, mask)
        if g is None: counts.append(0); continue
        n = 0
        for col in range(2, 65):
            if g[col] is not None and g[col] > 0: n += 1; per_zone[col] = per_zone.get(col, 0) + 1
        counts.append(n); yrs += n > 0
    three = sum(1 for v in per_zone.values() if v >= 3)
    lines.append(f"| {name} | {c['status']} | {yrs} | {' / '.join(map(str, counts))} | {three} | {oldn.get(name, 0)} | {c['note']} |"); tot_direct += three
lines += ['', f"Zone-crop pairs with a yield in three or more of the five years: {tot_direct}. In 2005-10, {sum(oldn.values())} pairs had an averaged yield, of which most needed the same three-year support.", '']
open(os.path.join(HERE, 'COVERAGE.md'), 'w').write('\n'.join(lines))
print('\n'.join(lines[:12])); print('...'); print(lines[-2])
