#!/usr/bin/env python3
"""make_pack: build the verification pack for Murray from the registers.

Run from the repository root:
  python3 -I qa/tools/make_pack.py            print the pack
  python3 -I qa/tools/make_pack.py --write    write qa/reports/pack_2026-11-07.md

Reads qa/claims_register.csv and qa/defects.csv (read only) and, for the header,
`git rev-parse --short HEAD` (read only). The Tier B sample uses a fixed seed, so
the same register gives the same sample.
"""
import csv, random, re, subprocess, sys
from collections import Counter, defaultdict

DATE = "2026-11-07"
SEED = 35
SAMPLE = 20
OUT = f"qa/reports/pack_{DATE}.md"
GOOD = ("independently verified", "Murray-verified")
LAYERS = {"1": "data", "2": "method", "3": "calculation", "4": "interpretation",
          "5": "literature", "6": "reproduction", "7": "uncertainty", "8": "editorial"}


def rows(path):
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def one_line(s, n=150):
    s = re.sub(r"\s+", " ", s).strip().replace("|", "/")
    return s if len(s) <= n else s[: n - 3].rstrip() + "..."


def reports(c):
    parts = [p.strip() for p in c["verifier_report"].split(";") if p.strip()]
    return [re.sub(r"^qa/reports/", "", p) for p in parts]


def route_count(c):
    return len({re.sub(r"\s*\(.*\)$", "", p) for p in reports(c)})


def defect_hits(c, defects):
    hits = []
    cid = re.compile(r"(?<![A-Za-z0-9])" + re.escape(c["id"]) + r"(?![A-Za-z0-9])")
    out = c["output_file"].strip()
    for d in defects:
        w = d["what"]
        if cid.search(w) or (out and out in w):
            hits.append(d["id"])
    return hits


def line(c, defects):
    status = c["status"]
    open_bits = []
    if status not in GOOD:
        open_bits.append("status: " + status)
    hits = defect_hits(c, defects)
    if hits:
        open_bits.append("defects " + ",".join(hits))
    script = c["script"] or "none"
    outf = c["output_file"] or "none"
    rep = "; ".join(reports(c)) or "none"
    val = (c["value"] + " " + c["unit"]).strip()
    return (f"| {c['id']} | {one_line(c['statement'])} | {one_line(val, 40)} | {script} -> {outf} "
            f"| {rep} | {status} | {'; '.join(open_bits) or 'nothing'} |")


HEAD = ("| id | statement | value | produced by (script -> output) | verifier reports | status | open |\n"
        "|---|---|---|---|---|---|---|")


def build():
    claims = rows("qa/claims_register.csv")
    defects = rows("qa/defects.csv")
    try:
        commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True,
                                text=True, check=True).stdout.strip()
    except Exception:
        commit = "unknown"
    L = []
    L.append(f"# Verification pack, {DATE}")
    L.append("")
    L.append(f"Commit: {commit}. Generated by `qa/tools/make_pack.py` from `qa/claims_register.csv` "
             f"and `qa/defects.csv`. Claims: {len(claims)}. Defects: {len(defects)}.")
    L.append("")
    L.append("## How to read this")
    L.append("")
    L.append("Every number and statement in the two papers is a row (a claim) in a register. Paper A is the "
             "results paper and paper B the methods paper. Each claim has a tier: A is a headline result or "
             "anything a reader would quote and needs two independent routes to agree; B is a supporting "
             "number needing one independent check; C is context. The status says how far the claim has been "
             "checked, from unverified through self-checked to independently verified. A route is a verifier "
             "report in `qa/reports/` that re-derived or re-checked the claim without using the producing "
             "script's own logic. Section 2 lists each Tier A claim on one line; the last column says what is "
             "still open (a status short of independently verified, or a defect that names the row or its "
             "output file). Section 3 lists the Tier A claims with fewer than two routes, which is what gate 2 "
             "cannot pass with. Section 4 lists every defect not yet fixed. Section 5 is a fixed sample of "
             "Tier B rows. You read every Tier A line, sample Tier B, and are not asked to re-derive.")
    L.append("")
    L.append("## 1. Counts")
    L.append("")
    for name, key in (("Paper", "paper"), ("Tier", "tier"), ("Status", "status")):
        L.append(f"**{name}**")
        L.append("")
        L.append(f"| {name.lower()} | claims |\n|---|---|")
        for k, v in sorted(Counter(c[key] for c in claims).items()):
            L.append(f"| {k} | {v} |")
        L.append("")
    L.append("**Paper by tier by status**")
    L.append("")
    L.append("| paper | tier | status | claims |\n|---|---|---|---|")
    for k, v in sorted(Counter((c["paper"], c["tier"], c["status"]) for c in claims).items()):
        L.append(f"| {k[0]} | {k[1]} | {k[2]} | {v} |")
    L.append("")

    A = sorted((c for c in claims if c["tier"] == "A"), key=lambda c: (c["id"][0], c["id"]))
    L.append(f"## 2. Tier A, one line per claim ({len(A)})")
    L.append("")
    L.append(HEAD)
    L += [line(c, defects) for c in A]
    L.append("")

    weak = [c for c in A if c["status"] not in GOOD or route_count(c) < 2]
    L.append(f"## 3. Tier A claims with fewer than two routes ({len(weak)})")
    L.append("")
    L.append("A claim is listed when its status is not `independently verified` or it names fewer than two distinct "
             "verifier reports.")
    L.append("")
    L.append("| id | status | reports | why |\n|---|---|---|---|")
    for c in weak:
        why = []
        if c["status"] not in GOOD:
            why.append("status not independently verified")
        n = route_count(c)
        if n < 2:
            why.append(f"{n} report" + ("" if n == 1 else "s"))
        L.append(f"| {c['id']} | {c['status']} | {'; '.join(reports(c)) or 'none'} | {', '.join(why)} |")
    L.append("")

    opn = [d for d in defects if d["fixed_in"].startswith(("open", "noted"))]
    L.append(f"## 4. Open items ({len(opn)})")
    L.append("")
    L.append("Defects whose `fixed_in` starts with open or noted, grouped by layer.")
    L.append("")
    by = defaultdict(list)
    for d in opn:
        by[d["layer"]].append(d)
    for lay in sorted(by):
        L.append(f"### Layer {lay}, {LAYERS.get(lay, '')} ({len(by[lay])})")
        L.append("")
        for d in by[lay]:
            L.append(f"- {d['id']} ({d['fixed_in']}): {one_line(d['what'], 400)}")
        L.append("")

    B = sorted((c for c in claims if c["tier"] == "B"), key=lambda c: c["id"])
    samp = sorted(random.Random(SEED).sample(B, min(SAMPLE, len(B))), key=lambda c: c["id"])
    L.append(f"## 5. Tier B sample ({len(samp)} of {len(B)}, seed {SEED})")
    L.append("")
    L.append(HEAD)
    L += [line(c, defects) for c in samp]
    L.append("")
    return "\n".join(L), claims, A, weak, opn


if __name__ == "__main__":
    text, claims, A, weak, opn = build()
    if "--write" in sys.argv:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {OUT}: {len(claims)} claims, {len(A)} Tier A, {len(weak)} below two routes, {len(opn)} open items")
    else:
        print(text)
