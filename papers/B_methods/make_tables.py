#!/usr/bin/env python3
"""Tables of paper B (methods), generated from results/ and analysis/ files; no number is typed.
Usage (repository root): python3 -I papers/B_methods/make_tables.py   -> papers/B_methods/tables.md
The header of tables.md names the commit it was made from; regenerate after any change to results/ (`cd web && npm run results`)."""
import csv, subprocess
rd = lambda p: list(csv.DictReader(open(p)))
M = lambda x: f'{float(x) / 1e6:.2f}'
commit = subprocess.run(['git', 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True).stdout.strip()
out = [f'# Paper B tables (generated by make_tables.py from commit {commit}; do not edit by hand)', '']
def cap(rel, zone, preset):
    for r in rd(f'results/{rel}.csv'):
        if r['zone'] == str(zone) and r['preset'] == preset: return float(r['capacity'])
# Table 1: the six cells, Australia
rng = {}
for rel in ('2025-mirror', '2025-fixed', '2025-improved'):
    for r in rd(f'results/ranges_{rel}.csv'):
        if r['zone'] == '1': rng[(rel, r['setting'])] = r
grid = [('Published method', '2011-corrected', '2025-mirror'), ('Corrected', '2011-fixed', '2025-fixed'), ('Improved', '2011-improved', '2025-improved')]
out += ['## Table 1. Capacity of Australia, millions of people: data vintage by method tier (2025 columns: base and 90% Monte Carlo range)', '',
        '| Method tier | 2011 short | 2025 short (range) | 2011 long | 2025 long (range) |', '|---|---|---|---|---|']
for name, r11, r25 in grid:
    f = lambda s: f"{M(cap(r25,1,s))} ({M(rng[(r25,s)]['p5'])} to {M(rng[(r25,s)]['p95'])})"
    out.append(f'| {name} | {M(cap(r11,1,"short"))} | {f("short")} | {M(cap(r11,1,"long"))} | {f("long")} |')
out += ['', f'Releases: {", ".join(g[1] + " and " + g[2] for g in grid)}. The 2011 cells have no range (their inputs were not sampled).', '']
# Table 2: effect of each module, in sequence
mods = ['biodiesel-yield', 'beef-carcase-yield', 'reserve-pro-rata', 'recycling-stage', 'loss-factors-australia', 'regional-beef-output', 'organic-ruminant-factor', 'dairy-good-land']
me = rd('results/method_effects.csv')
row = lambda v, p: next(r for r in me if r['vintage'] == v and r['zone'] == '1' and r['preset'] == p)
out += ['## Table 2. Effect of each method change, Australia, millions of people (alone / in sequence; corrections first, then improvements)', '',
        '| Change | Tier | 2011 short | 2011 long | 2025 short | 2025 long |', '|---|---|---|---|---|---|']
for m in mods:
    tier = 'correction' if m in mods[:2] else 'improvement'
    cells = []
    for v, p in (('2011', 'short'), ('2011', 'long'), ('2025', 'short'), ('2025', 'long')):
        r = row(v, p); cells.append(f"{float(r['effect_alone_' + m]) / 1e6:+.2f} / {float(r['effect_step_' + m]) / 1e6:+.2f}")
    out.append(f'| {m} | {tier} | ' + ' | '.join(cells) + ' |')
tot = []
for v, p in (('2011', 'short'), ('2011', 'long'), ('2025', 'short'), ('2025', 'long')):
    r = row(v, p); tot.append(f"{M(r['capacity_published'])} to {M(r['capacity_corrected'])} to {M(r['capacity_improved'])}")
out.append('| published to corrected to improved | | ' + ' | '.join(tot) + ' |')
out += ['', 'Each effect in sequence is the change when added after the modules above it; alone is the change when added to the published method only. The two differ because the modules interact (`interaction` column of `results/method_effects.csv`).', '']
# Table 3: drivers
NAME = {'sf': 'field-crop group factor', 'sh': 'vegetable, fruit and nut factors', 'meat': 'window of herd and meat data', 'meategg': 'meat and egg share of the diet', 'redmeat': 'red meat share of the diet',
        'fuel': 'liquid fuel per person', 'biofuel': 'biofuel share', 'timber': 'timber per person', 'orgfac': 'default organic yield factor', 'orgshare': 'organic share of land',
        'restable': 'resilience table', 'lfuel': 'long-term liquid fuel', 'lbench': 'long-term feeding benchmark'}
out += ['## Table 3. Share of the variance of Australia\'s capacity explained by each uncertain choice alone (improved cell)', '', '| Choice | Short term | Long term |', '|---|---|---|']
s = rng[('2025-improved', 'short')]; l = rng[('2025-improved', 'long')]
for k in sorted(NAME, key=lambda k: -max(float(s['influence_' + k]), float(l['influence_' + k]))):
    out.append(f"| {NAME[k]} | {float(s['influence_' + k]) * 100:.0f}% | {float(l['influence_' + k]) * 100:.0f}% |")
# Table 4: scale
sc = rd('results/scale_curve.csv')
out += ['', '## Table 4. Scale: the sum of the capacities of smaller units against the national capacity, short term (millions of people)', '',
        'Yield basis: `state` (the figure of the paper) gives every unit the yields and the irrigation and reserve settings of its state; `local` (the sensitivity) gives a unit the yields of its own NRM zone (`analysis/scale_curve_2025/README.md`).', '',
        '| Release | Yield basis | Level | Units | Sum of capacity | Share of national | Units over capacity |', '|---|---|---|---|---|---|---|']
for r in sorted(sc, key=lambda r: r['yield_basis'] != 'state'):
    if r['release'] in ('2011-fixed', '2025-fixed', '2025-improved') and r['preset'] == 'short' and r['land_basis'] == 'release' and r['level'] in ('Australia', 'State', 'NRM region'):
        out.append(f"| {r['release']} | {r['yield_basis']} | {r['level']} | {r['units']} | {M(r['sum_capacity'])} | {float(r['share_of_national']):.2f} | {r['units_over_capacity']} |")
# Table 5: nutrition
nv = [r for r in rd('analysis/nutrition_lp_2025/variants.csv') if r['release'] == '2025-improved' and r['zone'] == '1']
out += ['', '## Table 5. Nutrition-constrained diets, Australia, 2025 improved (`analysis/nutrition_lp_2025/variants.csv`)', '', '| Variant | Setting | Micronutrients | Capacity at the default diet | Capacity of the optimised diet | Gain |', '|---|---|---|---|---|---|']
for r in nv: out.append(f"| {r['variant']} | {r['preset']} | {r['with_micronutrients']} | {M(r['capacity_default'])} | {M(r['capacity_optimised'])} | {float(r['gain']):.2f} |")
open('papers/B_methods/tables.md', 'w').write('\n'.join(out) + '\n'); print('\n'.join(out))
